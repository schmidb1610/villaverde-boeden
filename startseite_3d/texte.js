const SPEICHER = "villaverde.sprache";       // auch von der Daten-Website gelesen und geschrieben

function gespeichert() { try { return localStorage.getItem(SPEICHER); } catch (e) { return null; } }

const wunsch = new URLSearchParams(location.search).get("lang") || gespeichert();
export const SPRACHE = wunsch in TEXTE ? wunsch : "de";
export const LOCALE = SPRACHE === "de" ? "de-DE" : "en-GB";
export const t = (k) => TEXTE[SPRACHE][k] ?? TEXTE.de[k] ?? k;

// Statische Texte im HTML setzen
document.documentElement.lang = SPRACHE;
for (const el of document.querySelectorAll("[data-t]")) el.textContent = t(el.dataset.t);
for (const el of document.querySelectorAll("[data-t-aria]")) el.setAttribute("aria-label", t(el.dataset.tAria));
for (const el of document.querySelectorAll("[data-t-title]")) el.title = t(el.dataset.tTitle);

// Sprachwechsel: speichern und neu laden, damit Nadeln, Panel und Einstieg neu entstehen.
// Aus dem Gelände heraus bleibt man im Gelände, im Einstieg startet er in der neuen Sprache neu.
for (const k of document.querySelectorAll("[data-sprachwahl]")) k.addEventListener("click", () => {
  try { localStorage.setItem(SPEICHER, SPRACHE === "de" ? "en" : "de"); } catch (e) { /* ohne Speicher weiter */ }
  history.replaceState(null, "", location.pathname + (k.closest("#intro") ? "" : "#gelaende"));
  location.reload();
});
